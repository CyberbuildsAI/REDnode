// Builds the player zip for Nexus Mods and GitHub releases from what the build staged.
//
//   .\tools\build-native.ps1
//   npm run overlay:package
//   npm run release:zip
//
// Output: native/build/release/REDnode-<version>.zip, laid out like the game folder, so
// Vortex, REDdeck or a player extracting it by hand into the game folder all put it in
// the same place:
//   red4ext/plugins/REDnode/REDnode.dll           the plugin
//   red4ext/plugins/REDnode/Scripts/              its redscript parts
//   red4ext/plugins/REDnode/host/                 the overlay host, with its own Electron
//   red4ext/plugins/REDnode/apps/<id>/            the samples listed in SAMPLES, all off at first
//   red4ext/plugins/REDnode/LICENSE.txt, THIRD-PARTY-NOTICES.txt, README.txt
//
// REDbridge is not in it: REDnode runs without it, and packages that use kernel.bridge()
// find the copy REDdeck or REDcode fetched (packages/overlay/redbridge.js).
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const version = readFileSync(join(repo, 'VERSION'), 'utf8').trim();
const plugin = join(repo, 'native', 'build', 'dist', 'red4ext', 'plugins', 'REDnode');
const deps = join(repo, 'native', 'build', '_deps');
const out = join(repo, 'native', 'build', 'release');
const stage = join(out, 'stage');
const target = join(stage, 'red4ext', 'plugins', 'REDnode');
const zip = join(out, `REDnode-${version}.zip`);

// The samples players get. Each starts off; the player switches it on in the launcher.
// The other apps in packages/overlay/apps are tests and stay in the repo.
const SAMPLES = ['hello-mod', 'ask-mod', 'kit', 'vitals', 'coords', 'perf'];

for (const need of ['REDnode.dll', 'Scripts', join('host', 'REDnode-overlay.exe')]) {
  if (!existsSync(join(plugin, need))) {
    throw new Error(`${need} is not staged. Run .\\tools\\build-native.ps1 and npm run overlay:package first.`);
  }
}

rmSync(out, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

cpSync(join(plugin, 'REDnode.dll'), join(target, 'REDnode.dll'));
cpSync(join(plugin, 'Scripts'), join(target, 'Scripts'), { recursive: true });
cpSync(join(plugin, 'host'), join(target, 'host'), { recursive: true });

for (const id of SAMPLES) {
  const from = join(repo, 'packages', 'overlay', 'apps', id);
  const manifest = join(from, 'rednode-app.json');
  if (!existsSync(manifest)) throw new Error(`Sample ${id} has no rednode-app.json`);
  cpSync(from, join(target, 'apps', id), { recursive: true });
  const m = JSON.parse(readFileSync(manifest, 'utf8'));
  m.open = false;
  writeFileSync(join(target, 'apps', id, 'rednode-app.json'), JSON.stringify(m, null, 2) + '\n');
}

// Licenses: REDnode's, and the code built into the plugin. Electron's and Chromium's are
// in host/ already (LICENSE, LICENSES.chromium.html); the host's npm packages keep theirs
// inside host/resources/app.asar.
cpSync(join(repo, 'LICENSE'), join(target, 'LICENSE.txt'));
const licenseOf = (dir) => {
  const src = join(deps, dir);
  if (!existsSync(src)) throw new Error(`${src} is missing. Run .\\tools\\build-native.ps1 first.`);
  return readdirSync(src)
    .filter((f) => /^(license|third_party_licenses)/i.test(f))
    .map((f) => readFileSync(join(src, f), 'utf8').trim())
    .join('\n\n');
};
const rule = '='.repeat(78);
writeFileSync(
  join(target, 'THIRD-PARTY-NOTICES.txt'),
  [
    `REDnode ${version} includes the following third-party software.`,
    '',
    'In REDnode.dll:',
    '  RED4ext.SDK (MIT), https://github.com/WopsS/RED4ext.SDK',
    '  miniaudio 0.11.25 (public domain or MIT No Attribution), https://github.com/mackron/miniaudio',
    '',
    'In host/:',
    '  Electron and Chromium: see host/LICENSE and host/LICENSES.chromium.html',
    '  The host\'s npm packages (the MCP SDK, zod and theirs): their licenses are in host/resources/app.asar',
    '',
    'host/resources/gameapi/game.d.ts lists the base game\'s type names and signatures,',
    'generated by REDnode from the game\'s reflection data, as in the published game API reference.',
    '',
    rule,
    'RED4ext.SDK',
    rule,
    licenseOf('red4ext_sdk-src'),
    '',
    rule,
    'miniaudio',
    rule,
    licenseOf('miniaudio-src'),
    '',
  ].join('\r\n'),
);
writeFileSync(
  join(target, 'README.txt'),
  [
    `REDnode ${version}: a Node.js modding framework for Cyberpunk 2077 (PC, single-player).`,
    '',
    'Needs: RED4ext and redscript. Some packages also need Codeware, TweakXL or ArchiveXL;',
    'the Mod Manager says which.',
    '',
    'Packages that read the game\'s archives also need REDbridge. Install REDdeck or REDcode',
    '(VS Code extensions) and let it download REDbridge once; REDnode finds that copy.',
    'Or set REDBRIDGE_EXE to a REDbridge.exe from github.com/Edgemodders/REDbridge (needs .NET 10).',
    '',
    'Press F10 in the game to open the overlay. Samples are in the launcher, switched off.',
    'Install REDnode packages into red4ext/plugins/REDnode/apps/<package>/.',
    '',
    'Docs: https://edgemodders.github.io/REDnode/',
    'Source: https://github.com/Edgemodders/REDnode',
    '',
  ].join('\r\n'),
);

// Windows' own tar writes zip files (-a picks the format from the name). Git's tar does not.
const tar = join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'tar.exe');
const packed = spawnSync(tar, ['-a', '-c', '-f', zip, 'red4ext'], { cwd: stage, stdio: 'inherit' });
if (packed.status !== 0) throw new Error('Zipping failed');

const count = (dir) =>
  readdirSync(dir, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? count(join(dir, e.name)) : 1), 0);
console.log(`${zip}: ${(statSync(zip).size / 1048576).toFixed(0)} MB, ${count(stage)} files`);
console.log(`Samples: ${SAMPLES.join(', ')}`);
